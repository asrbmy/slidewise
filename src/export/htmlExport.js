async function sha256b64(text) {
  const d = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  let s = ''; new Uint8Array(d).forEach((b) => { s += String.fromCharCode(b); }); return btoa(s);
}
export function slideTranscript(slide) {
  const parts = []; for (const o of walkTexts(slide.objects)) { const t = objectSearchText(o).trim(); if (t) parts.push(t); if (o.alt) parts.push('Image: ' + o.alt); }
  return parts.join('\n');
}
// slidePngs: array of data: URLs of PNG (generated by the caller from the canvas renderer)
export async function buildHtmlSlideshow(deck, slides, slidePngs) {
  const styleHash = await sha256b64(CSS), scriptHash = await sha256b64(JS);
  const csp = `default-src 'none'; img-src data:; style-src 'sha256-${styleHash}'; script-src 'sha256-${scriptHash}'; base-uri 'none'; form-action 'none'`;
  const imgs = slides.map((s, i) => `<img class="s tr${i === 0 ? ' on' : ''}" src="${slidePngs[i]}" alt="${esc(`Slide ${i + 1}: ${slideTitle(s)}`)}" draggable="false">`).join('\n');
  const notes = slides.map((s, i) => `<section><h2>Slide ${i + 1}</h2><pre>${esc(slideTranscript(s))}</pre>${s.notes ? `<h3>Speaker notes</h3><pre>${esc(s.notes)}</pre>` : ''}</section>`).join('\n');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${csp}"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="generator" content="Slidewise"><title>${esc(deck.name)}</title><style>${CSS}</style></head>
<body><div id="stage" role="group" aria-roledescription="slideshow" aria-label="${esc(deck.name)}">
${imgs}
</div><div id="cov" aria-hidden="true"></div><div id="bar" role="presentation"></div>
<div id="hud"><button id="prev" type="button" aria-label="Previous slide">◀</button><button id="next" type="button" aria-label="Next slide">▶</button><button id="fs" type="button">Fullscreen</button></div>
<div id="live" class="sr" role="status" aria-live="polite"></div>
<div id="notes" class="sr">${notes}</div>
<script>${JS}</script></body></html>`;
}
